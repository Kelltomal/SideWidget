"""Train local Russian intent and file-subject models. See train.py for dependencies."""

from random import Random
from train import export, features


SUBJECTS = {
    'Счета': 'счета|платежные счета|счетам на оплату|инвойсы|счета поставщиков|выставленные счета|инвойсам',
    'Скриншоты': 'скриншоты|скрины|снимки экрана|снимки с экрана|скриншотам|захваты экрана',
    'Документы': 'документы|текстовые файлы|офисные документы|таблицы и документы|документам',
    'Изображения': 'изображения|картинки|фотографии|фотки|фото|графические файлы',
    'Архивы': 'архивы|архивчики|сжатые файлы|архивные файлы|зипы|архивам',
    'Логи': 'логи|журналы|журналы событий|файлы журналов|логам',
    'Видео': 'видео|видеозаписи|видеоролики|ролики|видосы|видеофайлы',
    'Медиа': 'медиа|медиафайлы|мультимедиа|аудио и видео|мультимедийные файлы',
    'Игры': 'игры|игрушки|игровые ярлыки|ярлыки игр|запуски игр',
    'Программы': 'программы|приложения|проги|ярлыки программ|утилиты|софту|софт',
    'Скрипты': 'скрипты|батники|командные файлы|сценарии запуска|пакетные файлы',
    'Запуски_серверов': 'запуски серверов|серверные ярлыки|ярлыки для запуска сервера|запускалки серверов|ярлыки серверов',
    'Файлы': 'все файлы|всё с рабочего стола|файлы на столе|файлы|все элементы рабочего стола',
}

PATTERNS = {
    'year': 'разбей {x} по годам|раскидай {x} по годам|распредели по году {x}|для {x} сделай папку на каждый год|хочу разбивку {x} по годам|сделай группировку {x} по году|сгруппируй {x} по году выпуска|отдельная папка для каждого года у {x}|годовые папки для {x}|рассортируй по годам {x}|пусть у {x} будет своя папка для каждого года',
    'topic': 'разбери {x} по темам|распредели {x} по смыслу|сортируй {x} по содержанию|сгруппируй {x} по тематике|разложи {x} по содержанию|нужна разбивка {x} по тематике|хочу распределить {x} по смыслу',
    'keep': 'пусть {x} остаются на столе|{x} пусть останутся там же|пускай {x} лежат как раньше|оставь как есть {x}|{x} не трогай|пропусти {x}|сохрани на месте {x}|{x} остаются без изменений|пускай {x} лежат где лежали|оставь {x} в покое|{x} оставь там где они есть|пускай {x} остаются как есть',
    'move': 'собери {x} в папку|отправь в папку {x}|сложи {x} вместе в папку|мне надо перенести {x} в каталог|положи {x} в папку|отдельно сложи {x} в папку|снеси {x} в папку|закинь {x} в папку|пусть {x} будут в папке|для {x} выдели отдельную папку|собрать {x} в отдельную папку|размести {x} в каталоге',
}

def main():
    random = Random(441)
    intent, subject = [], []
    for label, phrases in SUBJECTS.items():
        for phrase in phrases.split('|'):
            for action, patterns in PATTERNS.items():
                variants = patterns.split('|')
                if action == 'keep':
                    variants += ['{x} пусть останутся как есть', 'пусть {x} будут без изменений',
                                 'оставь {x} как есть', 'пусть {x} лежат на прежнем месте']
                for pattern in variants:
                    line = pattern.format(x=phrase)
                    for prefix in ('', 'пожалуйста ', 'можешь ', 'хочу чтобы '):
                        text = features(prefix + line)
                        intent.append(f'__label__{action} {text}')
                        subject.append(f'__label__{label} {text}')
            for pattern in ('удали {x}', 'открой {x}', 'найди {x}', 'скопируй {x}', 'покажи {x}',
                            'не нужно раскладывать {x} по годам', 'запусти {x}', 'отправь по почте {x}'):
                intent.append('__label__unknown ' + features(pattern.format(x=phrase)))
    for line in ('как дела', 'что нового', 'старые вещи', 'все полезное', 'сделай удобно', 'мой рабочий стол',
                 'сортировка потом', 'убери ненужное', 'разложи важное по годам', 'все хорошее пусть лежит на месте'):
        for _ in range(30):
            subject.append('__label__unknown ' + features(line))
            intent.append('__label__unknown ' + features(line))
    for name, rows in (('intent', intent), ('subject', subject)):
        random.shuffle(rows)
        export(rows, 'desktop-prompt-' + name, ('разложи счета по годам', 'снимки экрана пусть останутся на месте'))


if __name__ == '__main__':
    main()
